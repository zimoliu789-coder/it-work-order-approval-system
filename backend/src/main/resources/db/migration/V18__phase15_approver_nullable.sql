--  · 动态审批流程（自定义申请第二期） —— 补丁
-- V18__phase15_approver_nullable.sql
--
-- 为什么需要这个补丁
-- ---------------------------------------------------------------------
-- V17 给 order_approval_nodes 加了 node_key / node_name / condition_desc，
-- 并设计为「条件分支未命中的节点同样落库、状态置 SKIPPED」——这样详情页能把
-- 「没走的那条路」连同原因一起画出来（否则事后没人能解释「为什么这笔单没经过财务审批」）。
--
-- 但 V17 漏了一件事：**未命中的节点从来没有产生过审批人**，它的 approver_id 天然是 NULL，
-- 而这一列从一期起就是 NOT NULL。结果是：
--   命中路径上的节点写入正常；一旦某笔单走的是「绕开某节点」的分支，
--   写入该 SKIPPED 行就会抛
--     java.sql.SQLException: Field 'approver_id' doesn't have a default value
--   → DataIntegrityViolationException → 接口 500。
--
-- 这是一个**只在特定表单数据下才出现**的缺陷：金额大于阈值时一切正常，
-- 金额小于阈值时提交直接 500。单测（不连库）与静态评审都看不到它，
-- 是接口回归用真实数据跑出来的。
--
-- 修复方式：把 approver_id 放开为可空。语义上是更准确的一版 ——
-- 「这个节点从未指派过审批人」与「指派给某人」本来就是两种状态。
-- 对既有数据没有任何影响（借用单与 GROUP 模式的自定义单该列恒有值）。
--
-- 顺带为  的 PREV_ASSIGN（上一节点审批人指定）铺好路：
-- 该能力要求节点在提交时 approver_id = NULL（待上一节点审批时才指派），
-- 同样依赖这一列可空。
--
-- 规范依据：第 13.2 章 快照语义｜第 13.3 章 审批流转
-- =====================================================================

ALTER TABLE `order_approval_nodes`
  MODIFY COLUMN `approver_id` BIGINT DEFAULT NULL
      COMMENT '审批人 user_id（快照固化）；条件分支未命中的 SKIPPED 节点为 NULL，表示从未指派审批人';
