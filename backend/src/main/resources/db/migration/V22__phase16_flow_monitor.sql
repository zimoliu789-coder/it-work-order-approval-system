-- =====================================================================
--  ·  · M7（流程监控）
-- V22__phase16_flow_monitor.sql
-- 企业内部设备借用工单系统
--
-- 覆盖需求（需求方 2026-09-23 确认"归属方案 = 加列落库"）：
--   流程监控需要把工单归属到「流程模板」，才能回答"每个模板的工单量 / 平均审批时长 / 瓶颈节点"。
--   本期补上这个缺失的归属指针，并开放只读权限码 flow_monitor:view。
--
-- ---------------------------------------------------------------------
-- 设计要点（为什么这样做）
-- ---------------------------------------------------------------------
--  A. **为什么必须加列，而不是靠快照反查**。
--     `orders.approval_flow_json` 只是定义快照，**不含模板 id / 版本 id**；
--     而 `ApprovalFlowServiceImpl.deleteFlow()` 会连同 `approval_flow_version` 行一起物理删除。
--     实测（2026-09-23，79 单中 10 单走过流程）：用「快照 ≡ 已发布版本定义」做规范化 JSON
--     指纹匹配，命中 **0 条** —— 全部变成孤儿。原因有二：① 模板被删后版本行不在了；
--     ② 即使版本行还在，快照是「求值/物化之后」的形态（字段顺序、null 归一都会漂移），
--     指纹相等是脆弱的。两个原因叠加，决定了"反查"方案在真实数据上不可用。
--
--  B. **加的是「版本 id」而不是「模板 id」**。与 V20（biz_group 绑版本）、
--     及二期以来的既定锚定语义一致：工单只引用**已发布版本**，模板后续怎么改都不漂移
--     （ 快照语义）。模板 id 可由版本行反查；反过来则做不到。
--
--  C. **同时冗余 `approval_flow_name`（模板名快照）**，是为了应对 A 里那个删表事实：
--     模板 / 版本被物理删除后，`approval_flow_version` 反查不到名字，
--     监控页会只剩一个孤零零的数字 id。存一份名字快照，让历史统计**始终可读**，
--     这与「节点行冗余 node_name」是同一取向（执行结果自带当时的展示名）。
--
--  D. **存量历史工单不回填**（需求方明确）。这些单的 `approval_flow_version_id` 保持 NULL，
--     监控页把它们归入「未归属」分组并显示条数 —— 不猜、不猜错，也不因为归属不明就把数据丢掉。
--     回填在技术上不可靠（见 A），做一次不可信的回填比不做更糟：它会让错误归属永久固化。
--
--  E. **版本物理删除语义保持不变**（需求方明确）。因此本表允许出现
--     「approval_flow_version_id 指向一行已不存在的记录」这种"悬空指针"——
--     这是**已知且接受**的状态，监控侧靠 C 的名字快照兜底显示，不做外键、不做级联。
--     刻意**不加外键约束**：加了会让 deleteFlow() 反过来被历史工单挡住，
--     把「删模板」变成一件需要先清理历史数据的高危操作。
--
--  F. **可空列 + 幂等授权，无破坏性变更**。回滚只需忽略这两列（旧代码 select * 也不会读它），
--     不需要删列、不需要改表。
-- =====================================================================

-- ---------------------------------------------------------------------
-- 一、orders 增量：流程模板归属（版本指针 + 模板名快照）
-- ---------------------------------------------------------------------
ALTER TABLE `orders`
  ADD COLUMN `approval_flow_version_id` BIGINT DEFAULT NULL
      COMMENT '提交时所用的已发布审批流程版本 approval_flow_version.id；NULL = 未走自定义流程模板（分组固定审批人表 / 借用单内置流程 / 存量历史工单）'
      AFTER `approval_flow_json`,
  ADD COLUMN `approval_flow_name` VARCHAR(64) DEFAULT NULL
      COMMENT '提交时的流程模板名快照（模板/版本被删除后监控页仍可显示名称）'
      AFTER `approval_flow_version_id`;

-- 监控页的「按模板聚合」全部命中此索引；同时支撑 deleteFlow() 的引用检查
-- （若将来要给管理员提示"该模板已被 N 张历史工单引用"）。
CREATE INDEX `idx_orders_afv` ON `orders` (`approval_flow_version_id`);


-- ---------------------------------------------------------------------
-- 二、RBAC：为内置 admin 角色补授 flow_monitor:view（幂等）
-- ---------------------------------------------------------------------
-- 为什么用 SQL 而不是改 RolePermissionInitializer 的默认集合：
--   初始化器受 `rbac_seeded` 一次性标记保护（V12 引入），在本系统已经跑过初始化的
--   环境里不会再次执行；只改代码默认集合，存量环境升级后 admin 会拿不到新菜单。
--   因此这里用「不存在才插入」把增量授权落成迁移，两种环境（新装 / 升级）结果一致。
-- 只授 view：流程监控是**只读分析视图**，没有维护动作，自然也没有 manage 码。
--   `flow_monitor:view` 归 admin（与 asset:report:view 同级的分析类权限），
--   超管不受影响：PermissionGuard 对 super_admin 恒定短路放行。
-- ---------------------------------------------------------------------
-- 注：`FROM DUAL` 不是装饰——MySQL 的「无表 SELECT」不允许直接跟 WHERE，
-- 缺了 DUAL 语句会在解析阶段失败（1064），迁移直接卡住。
INSERT INTO `sys_role_permission` (`role_code`, `perm_code`)
SELECT 'admin', 'flow_monitor:view' FROM DUAL
WHERE EXISTS (SELECT 1 FROM `sys_role` WHERE `role_code` = 'admin')
  AND NOT EXISTS (
      SELECT 1 FROM `sys_role_permission`
      WHERE `role_code` = 'admin' AND `perm_code` = 'flow_monitor:view'
  );
