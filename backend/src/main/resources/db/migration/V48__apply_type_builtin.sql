-- =====================================================================
-- V48__apply_type_builtin.sql
--
-- 申请类型支持「系统内置」类型（借用设备 / 故障报修）
--
-- <h2>它解决什么问题</h2>
-- 「提交申请」页一直有 7 张卡片，其中「借用设备」「故障报修」是**代码内置**的两类
-- （借用要临时锁设备 + 生成审批快照，报修要建故障记录，都不是通用表单能表达的），
-- 它们不产生 apply_type 记录；而「申请类型管理」页只列 apply_type 里的 5 类。
-- 于是同一个系统里，两个页面给出两份不同的「申请类型清单」——管理员据此做配置时无从对照。
--
-- 本次把这两类补进 apply_type 表：管理页与提交页口径一致，
-- 且管理员能调整它们的「表单说明」与「审批流程」。
--
-- <h2>为什么这里只有 DDL，没有 INSERT 种子</h2>
-- 与 {@code PresetApplyCatalog} 同一取舍：种子走**代码**（{@code BuiltInApplyInitializer}），
-- 用一次性标记 {@code builtin_apply_seeded:<typeCode>} 保证
-- 「管理员主动删掉后不会被重启复活」（本项目在权限播种上踩过这个坑）。
-- 用 SQL INSERT 则没有标记位，只能写成「不存在就补」那种会复活的写法。
-- 因此本脚本只做**结构变更**。
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) 内置标记：1 = 系统内置。管理页对它**不提供删除**（只保留启用 / 停用）。
--
--    为什么用列而不是靠 type_code 白名单判断：
--    「不可删除」是**数据事实**，应当跟着记录走。若靠代码里的编码清单判断，
--    一旦清单与数据不同步（改名、迁移遗漏），就会出现「页面上有删除按钮、
--    后端却拒绝」或反过来的静默不一致。
-- ---------------------------------------------------------------------
ALTER TABLE `apply_type`
    ADD COLUMN `built_in` TINYINT(1) NOT NULL DEFAULT 0
        COMMENT '是否系统内置类型：1 内置（借用设备 / 故障报修），不可删除' AFTER `status`;

-- ---------------------------------------------------------------------
-- 2) 内置类型的表单由**代码**提供（借用表单 / 报修表单都是内置页面），
--    不是可配置的表单模板，因此放开 NOT NULL。
--
--    注意这不等于放松校验：服务层对**非内置**类型仍然强制
--    「必须绑定一个已发布的表单版本」（与一期口径一致）。
--    换句话说，约束从「数据库列级」上移到「服务层按类型分支」——
--    因为现在确实存在「没有表单模板也合法」的类型。
-- ---------------------------------------------------------------------
ALTER TABLE `apply_type`
    MODIFY COLUMN `form_template_version_id` BIGINT NULL
        COMMENT '关联的表单模板版本（必须为已发布版本）；系统内置类型为 NULL：表单由代码提供';
