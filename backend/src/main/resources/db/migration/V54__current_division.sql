-- =====================================================================
-- V54 · 「当前所在分部」落到单据上（D5.1 ~ D5.3）
-- 企业内部设备借用工单系统
--
-- 背景：D5 要求借用 / 报修表单新增「当前所在分部」——
--   · 下拉只列**启用的一级分部**，不可手输，员工可手动改；
--   · 默认值自动预填：今天在出差中 ⇒ 出差单的目标分部；否则 ⇒ 人事主部门所属的一级分部；
--   · 取值来源必须可审计：人事主部门 / 出差自动带入 / 用户手动修改。
--
-- ---------------------------------------------------------------------
-- 设计要点
-- ---------------------------------------------------------------------
--  A. **两列而不是一列**：current_division_id 回答「派给谁」，
--     division_source 回答「这个值是系统给的还是人改的」。
--     只存 id 的话，事后无法区分「员工确认了预填值」与「员工改成了别的分部」——
--     而后者恰恰是审计要看的（是不是有人在故意把单子导向某个组）。
--
--  B. **不加外键**：部门允许被删除（成员调走、子部门清空后即可删）。
--     历史工单必须永远可读，加外键会让「删部门」被历史单据挡住。
--     悬空由「读不到就显示 -」兜底，与 apply_type_id 的处理一致。
--
--  C. **允许为空**：存量工单没有这个信息，回填无意义（当时的组织架构已不可考），
--     因此不回填、也不设默认值。新单由服务端在提交时写入。
--
--  D. **报修单也要存**：device_fault 是独立于工单的业务记录（报修不产生工单），
--     如果只在 borrow_order 上存，报修这条路的分部信息就丢了；
--     而报表「各分部报修量」正是要按它聚合。
--
-- 回滚：deploy/scripts/rollback/V54__rollback_current_division.sql
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 借用 / 自定义工单
-- ---------------------------------------------------------------------
ALTER TABLE `borrow_order`
    ADD COLUMN `current_division_id` BIGINT NULL
        COMMENT '当前所在分部 id（一级分部；决定处理小组匹配起点）',
    ADD COLUMN `division_source` VARCHAR(16) NULL
        COMMENT '分部取值来源：HR_PRIMARY 人事主部门 / TRIP_PREFILL 出差自动带入 / MANUAL 手动修改';

-- 按分部统计与「某分部漏配处理组」排查都要用到，加索引避免全表扫
ALTER TABLE `borrow_order`
    ADD KEY `idx_current_division` (`current_division_id`);

-- ---------------------------------------------------------------------
-- 2. 设备故障记录（报修不产生工单，只能落在这里）
-- ---------------------------------------------------------------------
ALTER TABLE `device_fault`
    ADD COLUMN `current_division_id` BIGINT NULL
        COMMENT '当前所在分部 id（一级分部；上报时填报）',
    ADD COLUMN `division_source` VARCHAR(16) NULL
        COMMENT '分部取值来源：HR_PRIMARY / TRIP_PREFILL / MANUAL';

ALTER TABLE `device_fault`
    ADD KEY `idx_current_division` (`current_division_id`);
