--  · （：系统参数按业务域重组）
-- V37__phase19_system_copyright.sql
-- 企业内部设备借用工单系统
--
-- 覆盖需求：
--   ① 系统参数新增一项 —— system.copyright（版权文字，默认空串）；
--   ② 复用既有 system_config 表，**不新建表、不加列**。
--
-- ---------------------------------------------------------------------
-- 设计要点（为什么这样做）
-- ---------------------------------------------------------------------
--  A. **为什么需要一个「版权文字」参数**。
--     把「基础设置」这一组定义为「站点品牌 + 文件存储 + 附件与导出」，
--     其中站点品牌除名称、图标之外还要求一行版权声明（登录页与侧边栏底部）。
--     本参数就是它的落点。
--
--  B. **为什么默认值是空串，而不是「© 2026 XX公司 版权所有」这样的占位文案**。
--     参数一旦预置文案，管理员在界面上看到「已经有值」时多半不会去改 ——
--     结果是每个部署单位都被默认挂上一行他们没写过的版权声明。
--     空串的语义是「不显示这一行」，由前端按空串判断是否渲染。
--     注意：这与 system.site-name 的口径**刻意不同**（那个必须非空，
--     因为 <title> 不能为空；版权只是页脚一行小字，空着完全正常）。
--
--  C. **为什么允许为空还要在 ConfigRules 里登记它**。
--     不登记也能保存（未登记键「不做值域校验、原样保存」），
--     但那样就绕开了 500 字的长度上限。版权会渲染进登录页与侧边栏底部，
--     超长值会把布局撑坏，因此必须让统一的长度校验对它生效。
--
--  D. **为什么 editable 仍写 1（而不是 0）**。
--     与 V25 同源：`editable=0` 会让 `updateValues` 对**所有人**（含 administrator）
--     拒绝写入。本项的规则是「只有内置超管能改，其他超管 / admin 只读置灰」——
--     这是**按调用者**区分的权限，不是按参数区分的。
--     因此 DB 层保持可写，把「谁可以写」交给服务层按当前登录者判定
--     （见 SystemConfigServiceImpl#updateValues 与 #listForAdmin）。
--
--  E. **为什么用 `INSERT ... SELECT ... FROM DUAL WHERE NOT EXISTS`（照 V16/V22/V23/V24/V25 的幂等模式）**。
--     迁移可能被重复执行（库重建、手工修复）；普通 INSERT 会撞 uk_system_config_key
--     唯一键导致整个迁移失败、库停在半途。
--     注：`FROM DUAL` 不是装饰 —— MySQL 的「无表 SELECT」不允许直接跟 WHERE，
--     缺了它会在解析阶段报 1064。
--
--  F. **为什么 config_group 仍取 `site` 而不是新的 `basic`**。
--      把参数页的三张卡（站点品牌 / 文件存储 / 附件与导出）并成了
--     「基础设置」，但那只改了**参数目录（SystemConfigCatalog）里的卡片编码**。
--     `config_group` 这一列只被旧的扁平接口 `/api/system/configs` 用作排序，
--     卡片式参数页根本不读它。改这一列会让既有回归脚本里
--     「config_group IN ('mail','sms','storage')」这类**数据断言**失效，
--     而收益为零 —— 因此刻意保持与 V25 一致。
--
--  G. **回滚方式**。删除这一行即可（`DELETE FROM system_config WHERE config_key = 'system.copyright'`），
--     代码侧 siteCopyright() 会回落到空串，界面不再显示版权行，不会 500。
-- =====================================================================

INSERT INTO `system_config` (`config_key`, `config_value`, `config_group`, `config_desc`, `editable`)
SELECT 'system.copyright', '', 'site',
       '版权文字：显示在登录页与侧边栏底部的一行小字，例如「© 2026 XX公司 版权所有」。留空则不显示。', 1
  FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM `system_config` WHERE `config_key` = 'system.copyright');
