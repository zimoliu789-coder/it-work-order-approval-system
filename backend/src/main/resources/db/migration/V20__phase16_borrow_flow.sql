-- 企业内部设备借用工单系统
--
-- 覆盖需求（需求方 2026-09-22 确认 Q1）：
--   让**借用单**也能走  的动态审批流程（条件分支 / 抄送 / 时限 / 直属领导 / 上一节点指定），
--   而不再只能走「业务分组固定审批人表」。绑定点 = **业务分组**。
--
-- ---------------------------------------------------------------------
-- 设计要点（为什么这样做）
-- ---------------------------------------------------------------------
--  A. **加列而不加新表、不加外键**。绑定点复用业务分组：一个分组要么走固定审批人表
--     （本期之前的行为），要么整体走一条已发布的流程版本。这正是"配置型引用"，
--     与 apply_type.approval_flow_version_id / app_type.form_template_version_id 同构，
--     因此沿用同一约定：**一律用应用层校验，不加数据库外键**（避免流程版本被引用后
--     无法清理，也便于历史留痕）。
--
--  B. **可空是零回归的载体**。本列 DEFAULT NULL，存量业务分组全部为 NULL →
--     借用单仍走原 buildSnapshot 固定审批人表，读写路径逐行不变。
--     借用单的"旧口径"与"新口径"就此天然共存，无需数据回填。
--
--  C. **只存"版本 id"而不是"流程 id"**。放流程 id 会引入"该用哪一版"的二次解释
--     （模板随时会发布 v2），而同项目的 apply_type / 表单模板一律锚定到**版本**，
--     以保证"工单提交后，其审批口径不因模板后续修改而漂移"（ 快照语义）。
--     这里保持一致，避免出现第二种锚定语义。
--
--  D. **索引列名沿用项目既有的 idx_<表缩写>_<语义> 风格**（与 idx_apply_type_afv 对齐）。
-- =====================================================================

-- ---------------------------------------------------------------------
-- biz_group 增量：绑定的借用审批流程版本
-- ---------------------------------------------------------------------
ALTER TABLE `biz_group`
  ADD COLUMN `approval_flow_version_id` BIGINT DEFAULT NULL
      COMMENT '绑定的已发布审批流程版本 approval_flow_version.id；NULL = 借用单走分组固定审批人表（本期之前的行为）'
      AFTER `final_handler_group_id`;

CREATE INDEX `idx_biz_group_afv` ON `biz_group` (`approval_flow_version_id`);
