-- =====================================================================
--  · ：附件保留期清理（「已删工单附件保留」）
-- V29__phase18_attachment_deleted_at.sql
-- 企业内部设备借用工单系统
--
-- 覆盖需求：
--   给 attachments 增加「逻辑删除时间」，使「附件删除后再保留 N 天」这条
--   保留期语义**有据可依**（N 取自系统参数 attachment_retention_days，默认 30）。
--
-- ---------------------------------------------------------------------
-- 设计要点（为什么这样做）
-- ---------------------------------------------------------------------
--  A. **为什么必须有 deleted_at，而不是复用 created_at**。
--     保留期的语义是「从**删除那一刻**起再保留 N 天」——这是误删恢复的最后窗口。
--     而 attachments 原有列只有 created_at（上传时间）与 deleted（0/1 布尔）。
--     若用 created_at 判定，会得到一个荒谬的结果：一个上传于半年前、**昨天刚被删除**的
--     附件（created_at 早已超出保留期）会在今晚 03:00 的清理中立刻被物理删除，
--     「删除后还能恢复 30 天」这条承诺形同虚设，且用户看到的是
--     「我刚删的东西怎么连回收机会都没有」。
--     因此删除时间必须单独记录，不能从既有列推导。
--
--  B. **为什么把「是否用 @TableLogic」保持原样，只加一列**。
--     MyBatis-Plus 的逻辑删除只写 deleted 标记，不认识额外的时间列。
--     本迁移刻意**不改动 deleted 的用法**（既有查询、唯一性判定、孤儿清理全部依赖它），
--     只让 AttachmentServiceImpl#delete 在置 deleted=1 的同时写 deleted_at。
--     这样「逻辑删除」这条既有链路的行为完全不变，新增的只是一个可观测的时间戳。
--
--  C. **存量软删记录用 created_at 兜底填 deleted_at（幂等）**。
--     库中已有历史软删行（演示 / 回归产生的），它们的 deleted_at 为 NULL。
--     若让清理任务跳过 NULL，这些行会**永远**留在表里；若让任务把 NULL 当「很久以前」
--     处理，又会立刻删掉它们 —— 两者都不可接受。
--     兜底成 created_at 消除了 NULL 这一第三态：每行都有一个可用时间，
--     且既有数据（上传日期在最近 30 天内）自然落在保留期内，不会被本次上线误伤。
--     `AND deleted_at IS NULL` 是幂等护栏：迁移若被重跑（库重建 / 手工修复），
--     不会把已经填好的值覆盖成 created_at。
--
--  D. **不新增索引**。
--     清理任务的判定是 `deleted = 1 AND deleted_at < ?`，但附件表规模在
--     500 员工 / 1000 设备的设计容量下是万级，且任务每天只跑一次、全表扫描成本可忽略。
--     为「每天一次的全表扫描」加一个写放大与维护成本的索引并不划算 ——
--     与 V28 头注释里「不加无收益的写入」同一取舍。
--
--  E. **回滚方式**（纯加列，回滚即删列；deleted_at 只是观测数据，删掉不影响任何逻辑）：
--     ALTER TABLE `attachments` DROP COLUMN `deleted_at`;
--     回滚后：AttachmentRetentionCleanupService 的 SQL 会因缺列而报错 ⇒
--     **必须同时停用该定时任务**（或回滚代码），因此生产回滚应当以「回滚代码包」为主、
--     删列为辅。
-- =====================================================================

ALTER TABLE `attachments`
    ADD COLUMN `deleted_at` DATETIME NULL DEFAULT NULL
        COMMENT '逻辑删除时间（ 保留期清理据此判定；历史数据按 created_at 兜底）'
        AFTER `deleted`;

-- 存量软删记录：用上传时间兜底，消除「deleted_at 为 NULL」这一第三态（见设计要点 C）
UPDATE `attachments`
   SET `deleted_at` = `created_at`
 WHERE `deleted` = 1
   AND `deleted_at` IS NULL;
