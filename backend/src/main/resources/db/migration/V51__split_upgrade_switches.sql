-- =====================================================================
-- V51__split_upgrade_switches.sql
--
-- 把「在线升级」的单一总开关拆成两个独立开关
--
-- <h2>为什么要拆</h2>
-- V49 引入了一个总开关 upgrade_enabled，页面按「运维代理是否就绪」**二选一**
-- 显示入口：代理就绪只显示「一键在线升级」，未就绪只显示「上传升级包」。
-- 这个设计的前提是「执行方式是一个客观事实」—— Docker 部署下上传包确实无效。
--
-- 但实际使用中它有两个问题：
--   ① 两条路径**无法同框验证**（想确认上传链路是否正常，只能把 agent 停掉再看页面）；
--   ② 「就绪」是**运行时**状态，会随时间变化，页面入口跟着跳来跳去，管理员难以预期。
--
-- 需求方 2026-10-13 明确：**两个入口都要常显，各自独立开关，且默认都关闭。**
-- 因此拆成两个键，执行方式仍是客观事实（在卡片内以提示说明），但**可见性与可用性
-- 交由管理员显式决定**，而不是由心跳推断。
--
-- <h2>为什么默认值都是 0（关闭）</h2>
-- 与 V49 / V39（备份）/ V38（主备）同一取向：
-- **会改变系统运行形态的能力，默认都不开启。**
-- 「能上传/能在线升级」等价于「能替换服务器上的可执行文件」，即代码执行能力 ——
-- 装好 ≠ 该打开。要用时到「系统设置 → 在线升级」页把对应开关拨开。
--
-- <h2>旧值怎么办：迁入两个新键，而不是丢弃</h2>
-- 与「不让既有部署静默失去能力」同一原则：若管理员此前已把总开关打开过，
-- 说明他确实需要在线升级能力 ⇒ 两个新键都置 1。
-- 若原本就是默认的 0，则两个新键保持 0 —— 与「默认关闭」的要求一致。
-- 迁移完成后 upgrade_enabled 不再被任何代码读取，故一并删除，
-- 避免页面上留着一个「拨了没反应」的死开关。
--
-- <h2>键名契约（与 V49 同一约定）</h2>
-- 键名跨三处必须逐字一致，任一处写错都不会编译报错，只会让开关「点了没反应」：
--   1) {@code UpgradeSettings.KEY_ONLINE_ENABLED} / {@code KEY_PACKAGE_ENABLED}；
--   2) 本脚本的初值与迁移；
--   3) 读取它的服务层（{@code UpgradeService#onlineEnabled()} / {@code #packageEnabled()}）。
--
-- <h2>刻意仍不进 SystemConfigCatalog</h2>
-- 这两个开关的界面入口在**在线升级页**上（每个入口卡片自带一个开关），
-- 配置目录不为它们登记 ⇒ 系统参数页不会重复渲染出第二份开关。
-- 数据库行保留 {@code config_group='upgrade'} 以便归类与导出。
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) 两个新开关，初始均为「关闭」
-- ---------------------------------------------------------------------
INSERT INTO `system_config` (`config_key`, `config_value`, `config_group`, `config_desc`, `editable`)
SELECT 'upgrade_online_enabled', '0', 'upgrade',
       '「一键在线升级」开关（拉取最新镜像并重建容器）。默认关闭；打开后升级页的在线升级入口才可用，且需要运维代理（ops-agent）正在运行。本开关不影响「上传升级包」入口。',
       1
  FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM `system_config` WHERE `config_key` = 'upgrade_online_enabled');

INSERT INTO `system_config` (`config_key`, `config_value`, `config_group`, `config_desc`, `editable`)
SELECT 'upgrade_package_enabled', '0', 'upgrade',
       '「上传升级包」开关（校验 → 备份 → 落 staging → 待应用）。默认关闭；打开后升级页的上传入口才可用。只服务非容器化部署：容器跑的是镜像，上传的 jar/dist 不会被加载。本开关不影响「一键在线升级」入口。',
       1
  FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM `system_config` WHERE `config_key` = 'upgrade_package_enabled');

-- ---------------------------------------------------------------------
-- 2) 迁移旧总开关的值：旧值若为「开」，两个新开关一起置「开」
--
-- 用自连接（多表 UPDATE）而不是子查询：MySQL 不允许在子查询里引用
-- 正在被 UPDATE 的同一张表，而自连接是可行的等价写法。
-- ---------------------------------------------------------------------
UPDATE `system_config` AS tgt
  JOIN `system_config` AS src
    ON src.`config_key` = 'upgrade_enabled'
   AND src.`config_value` = '1'
   SET tgt.`config_value` = '1'
 WHERE tgt.`config_key` IN ('upgrade_online_enabled', 'upgrade_package_enabled');

-- ---------------------------------------------------------------------
-- 3) 删除已废弃的总开关
--
-- 它不再被任何代码读取。留着只会让「系统参数」的原始列表里出现一个
-- 「拨了没反应」的死键；明确删掉比留一条语义已失效的记录更不容易误导。
-- ---------------------------------------------------------------------
DELETE FROM `system_config` WHERE `config_key` = 'upgrade_enabled';
