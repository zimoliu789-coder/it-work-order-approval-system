package com.enterprise.ticket.common.constant;

/**
 * 站内消息类型（ 新增， 触发场景表逐行对应）
 *
 * <p>消息类型的作用是让前端能按类型选择图标/颜色并决定点击后的跳转目标，
 * 同时为后续「按类型设置订阅开关」留出扩展位（ 预留企业 IM 扩展）。
 *
 * <p>本阶段已落地的类型：归还相关（{@link #RETURN_REQUESTED} / {@link #RETURN_CONFIRMED} /
 * {@link #DIMISSION_RETURN}）、到期与超时相关（{@link #BORROW_EXPIRE_WARNING} /
 * {@link #BORROW_DUE_REMINDER} / {@link #BORROW_AUTO_EXTEND} / {@link #BORROW_TIMEOUT}）。
 * 其余类型为 已定义、由其它阶段实现的通知场景，先行登记以便统一维护。
 */
public enum MessageType {

    // ---------------- 审批链路（ 已具备业务事实， 统一消息出口后可补齐推送） ----------------
    /** 新审批待办（接收人：当前步骤审批人） */
    APPROVAL_TODO("审批待办"),

    /** 审批通过（接收人：申请人） */
    APPROVAL_PASSED("审批通过"),

    /** 审批驳回（接收人：申请人，含驳回原因） */
    APPROVAL_REJECTED("审批驳回"),

    /** 待交付通知（接收人：被随机分配的实际执行人） */
    DELIVERY_TODO("待交付"),

    /** 工单被撤回（接收人：实际执行人） */
    ORDER_CANCELLED("工单撤回"),

    /** 工单转交（接收人：新的实际执行人，含转交备注，转交功能属后续阶段） */
    ORDER_TRANSFERRED("工单转交"),

    /**
     * 审批抄送（接收人：流程抄送节点的解析对象，）
     *
     * <p>抄送是「知会」而非「审批步骤」：提交时即解析即发送，不等流程走到抄送节点。
     * 正文含工单号与申请类型，点击跳转工单详情（抄送人可只读查看）。
     */
    ORDER_CC("审批抄送"),

    // ---------------- 归还链路 ----------------
    /** 申请人发起归还，提醒实际执行人确认收回 */
    RETURN_REQUESTED("归还申请"),

    /** 实际执行人确认收回完成（接收人：申请人） */
    RETURN_CONFIRMED("归还完成"),

    /** 员工离职联动回收，提醒实际执行人回收（ +  ） */
    DIMISSION_RETURN("离职回收"),

    // ---------------- 到期 / 顺延 / 超时 ----------------
    /** 到期前 N 天预警（接收人：申请人 + 实际执行人，） */
    BORROW_EXPIRE_WARNING("到期预警"),

    /** 到期当天再提醒一次（接收人：申请人 + 实际执行人，需求方 ） */
    BORROW_DUE_REMINDER("到期提醒"),

    /** 系统自动顺延（接收人：申请人 + 实际执行人，） */
    BORROW_AUTO_EXTEND("自动顺延"),

    /** 超时告警（接收人：实际执行人，执行人离职时转发 super_admin，） */
    BORROW_TIMEOUT("借用超时"),

    // ---------------- 其它（后续阶段） ----------------
    /** 延期审批结果 */
    EXTEND_RESULT("延期结果"),

    /** 密码被重置 */
    PASSWORD_RESET("密码重置"),

    // ---------------- 催办（；规范 V1.1 未覆盖） ----------------
    /** 审批催办（接收人：当前审批节点的审批人） */
    URGE_APPROVAL("审批催办"),

    /** 归还催办（接收人：借用人 / 申请人） */
    URGE_RETURN("归还催办"),

    // ---------------- 超管强制干预（；规范 V1.1 未覆盖） ----------------
    /**
     * 强制干预通知拆分为四个子类型（）
     *
     * <h2>为什么要拆</h2>
     * <p>改造前四类强制操作共用 {@code FORCE_OPERATION} 一个类型，消息中心里
     * 「你的工单被强制驳回」和「你的工单被强制转交」长得完全一样，
     * 用户必须点进正文才知道发生了什么。四类操作对接收者的含义差别很大
     * （驳回＝结束、终止＝结束且设备释放、改派审批/执行人＝换人接着办），
     * 混在一个类型里等于把「区分」这件事推给用户自己去读正文。
     *
     * 拆开之后还有个附带收益：可按类型做订阅开关与筛选统计
     * （例如超管想知道「本月强制终止了几单」）。
     *
     * <h2>历史数据</h2>
     * <p>旧的 {@code FORCE_OPERATION} 取值已由 Flyway V15 按消息标题
     * <b>全量迁移</b>到下面四个取值，因此枚举里不再保留该常量 ——
     * 留一个永远不会产生新数据的取值，只会在「消息类型」下拉里多出一个空选项。
     */

    /** 强制驳回（接收人：申请人） */
    FORCE_REJECT("强制驳回"),

    /** 强制终止（接收人：申请人、原执行人） */
    FORCE_TERMINATE("强制终止"),

    /** 强制转交审批（接收人：新审批人、原审批人、申请人） */
    FORCE_TRANSFER_APPROVAL("强制改派审批"),

    /** 强制转交执行人（接收人：新执行人、原执行人、申请人） */
    FORCE_TRANSFER_HANDLER("强制转交执行人"),

    // ---------------- 导出完成 ----------------
    /**
     * 导出文件生成完成（接收人：导出发起人）
     *
     * <p>：「导出超过 10000 条时异步生成文件，完成后站内消息通知下载」。
     * 消息正文带上导出类型与行数；下载地址是<b>后端鉴权端点</b>
     * （{@code /api/exports/{taskId}/download}），不是磁盘直链。
     */
    EXPORT_READY("导出完成"),

    // ---------------- 三波遗漏补做（第二波） ----------------
    /**
     * 审批超时提醒（接收人：长时间未处理的当前审批人）
     *
     * <p>与 {@link #URGE_APPROVAL} 的区别：催办是<b>申请人主动</b>发起的，
     * 而本类型由<b>定时任务</b>在节点超过阈值时长未处理时自动发出。
     * 两者刻意分开：消息中心里「谁在催我」与「系统提醒我卡住了」是不同性质的信息，
     * 混用同一类型会让用户无法区分「有人对我不满」和「该干活了」。
     */
    APPROVAL_TIMEOUT_REMIND("审批超时提醒"),

    /**
     * 设备工单对账告警（接收人：super_admin / admin）
     *
     * <p>每日对账发现「设备状态与工单状态不一致」时发出，正文列出具体设备与工单编号，
     * 便于运维直接定位处理（/ 状态机一致性）。
     */
    DEVICE_RECONCILE_ALERT("设备对账告警"),

    /**
     * 归还缺件 / 丢失告警（接收人：super_admin / admin）—— P0 新增
     *
     * <p>归还检查登记为「缺配件」或「丢失」时发出：前者是借用人的履约问题
     * （设备主体已回可用，但东西没还全），后者是资产暂时找不到。
     * 两者的共同点是 <b>需要管理员去做一件事 —— 追回或查找</b>，
     * 而这个动作在系统里没有任何其他提醒：工单此刻已经终结（RETURNED），
     * 不会再出现在任何人的待办里，不通知就会彻底沉底。
     *
     * <p>刻意独立成类型而不复用 {@link #RETURN_CONFIRMED}：后者发给<b>申请人</b>告知
     * 「已收回」（纯告知），本条发给<b>管理员</b>且<b>要求其行动</b> —— 收件人与动作都不同。
     * 也不复用 {@link #DEVICE_RECONCILE_ALERT}：对账告警指向「业务数据不一致」，
     * 本条指向「有一件实物没回来」。
     */
    RETURN_RECOVERY_ALERT("归还缺件/丢失告警"),

    // ---------------- Docker 部署 + 限流加固 ----------------
    /**
     * 运维作业告警（接收人：super_admin）
     *
     * <p>当前用于「数据库 / 附件 / 配置备份失败」：备份由独立容器内的 cron 执行
     * ，脚本拿不到应用内部的消息服务，因此失败时回调内部告警接口，
     * 由应用向全部超管发本类型消息。
     *
     * <p>刻意不复用 {@link #DEVICE_RECONCILE_ALERT}：对账告警指向「业务数据不一致」，
     * 而本类型指向「运维基础设施没跑成功」——两者的处理人和处置手段完全不同，
     * 混用会让运维在业务问题里翻找基础设施故障。
     */
    OPS_BACKUP_ALERT("备份失败告警"),

    // ---------------- ：直属领导兜底 ----------------
    /**
     * 直属领导解析失败兜底（接收人：申请人 / super_admin / admin）
     *
     * <p>某审批节点的规则是「申请人直属领导」，但解析不出可用的人
     * （未配置 / 已离职 / 账号停用 / 领导就是申请人本人）时，该节点由超级管理员兜底审批，
     * 同时向三方发出本条消息：<b>申请人</b>知情、<b>超管</b>接件、<b>管理员</b>去维护员工资料。
     *
     * <p>刻意与 {@link #APPROVAL_TODO} 分开：本条不是「你有活要干」，而是
     * 「配置缺了一环，已临时兜底」—— 收件人需要知道的是要去补配置，不是去审批。
     */
    APPROVAL_LEADER_FALLBACK("直属领导兜底"),

    // ---------------- ：主备双机热备告警（  [184]） ----------------
    /**
     * 主备节点断连（接收人：全部超级管理员）。
     *
     * <p>心跳超过 {@code ha_config.heartbeat_timeout_seconds} 未到达时发出。
     * 与 {@link #HA_SYNC_FAILED} 刻意分开：断连指向「这台机器联系不上了」
     * （可能是宕机、网络中断、进程被杀），而同步失败指向「两台都在、但数据没跟上」。
     * 两者的处置动作完全不同 —— 前者要去机房/看机器，后者通常只需看复制日志，
     * 混用会让维护人员从错误的方向开始排查。
     */
    HA_NODE_DISCONNECTED("主备节点断连"),

    /** 主备数据同步失败（接收人：全部超级管理员） */
    HA_SYNC_FAILED("主备同步失败"),

    /**
     * 主备发生切换（接收人：全部超级管理员）。
     *
     * <p>本类型<b>不分成功失败</b>：切换本身是一个必须让管理员知情的<b>事实</b>
     * （无论是自动接管还是计划性维护），而不是一个错误。它的价值在于
     * 「半夜三点换过主」这件事必须留下痕迹 —— 否则第二天管理员看到的
     * 一切正常，根本不知道昨天有个节点出过问题。
     */
    HA_SWITCHOVER("主备切换"),

    // ---------------- ：异常告警（接收人：全部超级管理员 + 可配运维收件人） ----------------
    /**
     * 未预期异常告警。
     *
     * <p>只承载**未预期异常 / 5xx**：业务异常（4xx）刻意不告警 ——
     * 否则用户填错一个字段就发一封邮件，告警疲劳之后真故障会被忽略。
     * 因此收到本类型消息时，它一定代表「代码里有没预料到的情况」，值得看。
     *
     * <p>与 {@link #OPS_BACKUP_ALERT} 分开：备份告警指向「某个运维作业没跑成功」，
     * 本类型指向「应用代码在某个请求上抛了没接住的异常」。前者查脚本，后者查代码。
     */
    EXCEPTION_ALERT("系统异常告警"),

    // ---------------- ：安全攻击告警（接收人：全部超级管理员） ----------------
    /**
     * 安全事件告警：账号被锁定、IP 被封禁、提权尝试。
     *
     * <p>刻意与 {@link #EXCEPTION_ALERT} 分开：安全事件往往**不是**异常
     * （登录失败是正常的 401，不是 5xx），但它比任何异常都更需要管理员知情。
     * 混在异常告警里会被「今天又抛了 300 个 NPE」淹没。
     */
    SECURITY_ALERT("安全事件告警");

    private final String label;

    MessageType(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }

    public static MessageType of(String value) {
        if (value == null) {
            return null;
        }
        for (MessageType type : values()) {
            if (type.name().equals(value)) {
                return type;
            }
        }
        return null;
    }

    /** 中文名，非法值原样返回，避免展示层出现 null */
    public static String labelOf(String value) {
        MessageType type = of(value);
        return type == null ? value : type.getLabel();
    }
}
