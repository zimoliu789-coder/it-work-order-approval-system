package com.enterprise.ticket.module.user.dto.vo;

import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * 管理员重置员工密码的结果（2026-09-20 ）
 *
 * <p>只有一个字段：系统生成的临时口令。
 *
 * <h2>为什么必须把口令回传给调用方</h2>
 * <p>改造前前端是拿一个写死的默认口令去调接口的 —— 界面上既不显示、
 * 也不提示，管理员点完「重置密码」后<b>根本不知道</b>该员工的新密码是什么，
 * 只能靠口口相传「试试某个默认口令」。这既不可靠（口令一旦改动就失效），
 * 也不安全（固定口令 + 全员相同 = 等于没设密码）。
 * 现在口令由服务端生成并在此返回，前端负责展示与复制，形成闭环。
 *
 * <h2>为什么由服务端生成，而不是让管理员输入</h2>
 * <p>需求允许二选一，这里选「系统生成」：管理员自行设定时极易随手用
 * 如 {@code 123456} 这类弱口令（本项目就见过），
 * 而临时口令的本质只是「一次性交接凭证」—— 交给系统生成，可保证必然满足
 * 密码策略的字符类型要求，也免去人为选择。该员工首次登录即被强制改密，
 * 因此这段口令的生命周期极短。
 *
 * <h2>一次性的含义</h2>
 * <p>本字段只在「重置成功」这一次响应里出现。系统不提供任何「再次查看」
 * 的接口，数据库里存的也只是 Argon2id 哈希 —— 管理员若误关弹窗，
 * 唯一后果是再重置一次（而不是口令被谁悄悄读走）。
 */
@Data
@NoArgsConstructor
@AllArgsConstructor
public class UserPasswordResetVO {

    /** 系统生成的临时口令（仅本次返回，事后不可查） */
    private String temporaryPassword;
}
