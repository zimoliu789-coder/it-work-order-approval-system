package com.enterprise.ticket.module.ha.dto;

import lombok.Data;

/**
 * 添加备节点请求（，  [171]）
 *
 * <p>说明：「点『添加备节点』，输入备机 IP 地址和管理员密码，点确认」。
 * 因此本 DTO 只有三个业务字段：IP、管理员密码、节点名（展示用）。
 *
 * <h2>⚠️ 关于「管理员密码」——本系统刻意不接收、不落库、不转发</h2>
 * <p>需求文档希望维护人员「不用敲任何命令」（需求 [172]），字面理解就是
 * 由系统拿着备机的 root / 管理员口令去远程完成部署。这一步在本项目里
 * <b>刻意不做</b>，理由必须写清楚，否则会被当成功能缺失：
 * <ol>
 *   <li><b>它要求本应用保存可登录其它机器的口令。</b>一旦落库，这个库就从
 *       「业务数据泄露」升级为「整个内网所有服务器的控制权泄露」——
 *       而本系统的库里有明文可解的密文列（{@code SecretCipher} 的密钥与
 *       JWT_SECRET 同源），泄漏面会被放大到不可接受的程度；</li>
 *   <li><b>它等价于一个内网横向移动工具。</b>一个持有 {@code ha:manage} 的账号
 *       就能让系统去连任意 IP 并执行部署脚本 —— 这条路径本身就是攻击面；</li>
 *   <li><b>正确形态已经存在</b>：{@code deploy/ha/scripts/} 下的脚本由运维
 *       在<b>目标机器上</b>以 root 执行（SSH 或物理登录），系统只负责
 *       <b>生成参数、给出逐步指引、接收心跳、展示状态</b>。</li>
 * </ol>
 * 因此本字段被<b>接收后立即丢弃</b>（不落库、不写日志、不进响应），
 * 仅用于「确认维护人员确实知道自己在做什么」这一交互语义；
 * 真正的握手由 {@code setup-replication.sh} 在目标机上完成。
 * 前端文案必须明确写出这一点，不能让维护人员以为系统真的会替他登录备机。
 *
 * <p>本字段刻意<b>不加</b> {@code @NotBlank}：允许留空提交（表示「我稍后手工部署」），
 * 避免把「不填密码」变成一条拦路的校验错误 —— 那会让本可按 3 步走完的流程卡在第 2 步。
 */
@Data
public class HaNodeCreateRequest {

    /** 备节点名称（展示用；留空则服务层按 IP 兜底生成，如「备节点 192.168.1.101」） */
    private String nodeName;

    /** 备节点 IP（必填，由 HaConfigValidator 校验格式） */
    private String nodeIp;

    /**
     * 备机管理员密码 —— <b>接收后立即丢弃</b>，不落库、不转发、不写日志。
     *
     * <p>保留该字段只是为了满足需求文档 [171] 的交互形态；
     * 详见类头注释「关于管理员密码」。
     */
    private String adminPassword;

    /** 备注（可选） */
    private String remark;
}
